import { chromium } from '@playwright/test'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import assert from 'node:assert/strict'

const root = resolve(import.meta.dirname, '..')
const out = join(root, 'test-results')
await mkdir(out, { recursive: true })
const base = 'http://127.0.0.1:4173'
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const report = {}
try {
  await page.goto(base, { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: /从源码出发/ }).waitFor()
  assert.equal(await page.locator('.project-card').count(), 5)
  await page.getByRole('tab', { name: 'MiniMind', exact: true }).click()
  assert.match(await page.locator('.workbench-code').innerText(), /loss.backward/)
  await page.getByRole('tab', { name: 'LangChain', exact: true }).click()
  assert.match(await page.locator('.workbench-code').innerText(), /chain = prompt/)
  await page.screenshot({ path: join(out, 'home-desktop.png'), fullPage: true })
  await page.getByRole('tab', { name: 'EasySpider', exact: true }).click()
  await page.getByRole('link', { name: /EasySpider.*进入项目讲义/ }).click()
  await page.locator('.VPDoc h1').waitFor()
  assert.match(await page.locator('.VPDoc h1').innerText(), /EasySpider/)
  await page.goto(base + '/openclaw/chapter-01', { waitUntil: 'networkidle' })
  assert.ok(await page.locator('.vp-doc img').count() > 0)
  const brokenImages = await page.locator('.vp-doc img').evaluateAll(imgs => imgs.filter(img => !img.complete || img.naturalWidth === 0).map(img => img.src))
  assert.deepEqual(brokenImages, [])
  await page.screenshot({ path: join(out, 'lecture-desktop.png'), fullPage: false })
  await page.getByRole('button', { name: /搜索课程讲义/ }).click()
  const search = page.locator('#localsearch-input')
  await search.fill('Runnable')
  await page.locator('.VPLocalSearchBox .result').first().waitFor({ timeout: 15000 })
  assert.match(await page.locator('.VPLocalSearchBox').innerText(), /LangChain|Runnable/)
  await search.fill('记忆')
  await page.locator('.VPLocalSearchBox .result').filter({ hasText: '记忆' }).first().waitFor({ timeout: 15000 })
  await page.screenshot({ path: join(out, 'search.png') })
  await page.keyboard.press('Escape')
  const files = JSON.parse(await readFile(join(root, 'docs/public/source-files.json'), 'utf8'))
  const key = Object.keys(files).find(k => files[k].name.endsWith('.ts'))
  await page.goto(base + '/source/?file=' + key + '#L20', { waitUntil: 'networkidle' })
  await page.locator('.source-code').waitFor()
  await page.waitForTimeout(200)
  assert.match(await page.locator('.source-filepath').innerText(), /\.ts/)
  assert.ok(await page.locator('.source-line.selected').count() > 0)
  await page.screenshot({ path: join(out, 'source-viewer.png') })
  await page.goto(base + '/llamafactory/ten-minutes', { waitUntil: 'networkidle' })
  assert.ok(await page.locator('.language-python').count() > 0)
  assert.ok(await page.locator('mjx-container').count() > 0, 'Mathematical formulas should be rendered')
  await page.goto(base + '/openclaw/chapter-06', { waitUntil: 'networkidle' })
  await page.locator('.mermaid-diagram svg').first().waitFor({ timeout: 20000 })
  await page.goto(base + '/minimind/', { waitUntil: 'networkidle' })
  assert.match(await page.locator('.vp-doc').innerText(), /基础与预训练/)
  assert.match(await page.locator('.vp-doc').innerText(), /PPO 采样与训练/)
  assert.doesNotMatch(await page.locator('.VPSidebar').innerText(), /课堂路线|历史稿|专题补充|第[一二三]课/)
  assert.doesNotMatch(await page.locator('.VPSidebar').innerText(), /阅读说明|完整讲义目录|源码与配套资料/)
  assert.equal(await page.locator('.VPSidebar a[href*="/minimind/b00-"]').count(), 1, 'Gradient note should stay on one page')
  assert.equal(await page.locator('.VPSidebar a[href*="/minimind/b21-"]').count(), 3, 'PPO source should have three thematic chapters')
  await page.goto(base + '/minimind/b00-01', { waitUntil: 'networkidle' })
  assert.match(await page.locator('.vp-doc h1').innerText(), /01 · 梯度、反向传播与梯度下降/)
  const equationHeading = page.locator('.vp-doc h2').filter({ has: page.locator('.heading-equation') }).first()
  await equationHeading.scrollIntoViewIfNeeded()
  assert.ok(await equationHeading.locator('mjx-container svg').count())
  assert.doesNotMatch(await equationHeading.innerText(), /\\omega|\\partial|\$/)
  assert.match(await page.locator('.VPDocAsideOutline').innerText(), /ω/)
  await page.screenshot({ path: join(out, 'minimind-heading-math.png') })
  await page.goto(base + '/minimind/', { waitUntil: 'networkidle' })
  await page.screenshot({ path: join(out, 'minimind-topics.png'), fullPage: true })
  await page.goto(base + '/minimind/b01-01', { waitUntil: 'networkidle' })
  assert.match(await page.locator('.vp-doc').innerText(), /预训练本质上只有一件事/)
  assert.doesNotMatch(await page.locator('.vp-doc').innerText(), /可以。给学生讲|下面这一版可以直接拿去上课/)
  const download = await page.locator('.original-note a').getAttribute('href')
  const downloadResponse = await page.request.get(base + download)
  assert.equal(downloadResponse.ok(), true)
  const markdown = await downloadResponse.text()
  assert.match(markdown, /预训练本质上只有一件事/)
  assert.doesNotMatch(markdown, /可以。给学生讲|下面这一版可以直接拿去上课/)
  assert.match(await page.locator('.original-note a').innerText(), /下载整理后 Markdown/)
  await page.goto(base + '/minimind/b19-01', { waitUntil: 'networkidle' })
  assert.doesNotMatch(await page.locator('.vp-doc').innerText(), /开源赚钱|OS社区|有多少同学/)
  await page.goto(base + '/minimind/b21-03', { waitUntil: 'networkidle' })
  assert.match(await page.locator('.vp-doc h1').innerText(), /采样、GAE 与 Actor-Critic 更新/)
  assert.match(await page.locator('.vp-doc h2').first().innerText(), /^1\./)
  assert.ok(await page.locator('.language-python').count() > 0)
  assert.ok(await page.locator('mjx-container').count() > 0)
  assert.match(await page.locator('.original-note').innerText(), /21.PPO训练代码讲义/)
  await page.screenshot({ path: join(out, 'minimind-lecture.png') })
  await page.goto(base + '/minimind/b11-01', { waitUntil: 'networkidle' })
  assert.equal(await page.locator('.language-math').count(), 0)
  assert.ok(await page.locator('mjx-container').count() > 20)
  await page.locator('mjx-container').first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: join(out, 'minimind-formulas.png') })
  await page.getByRole('button', { name: /搜索课程讲义/ }).click()
  await page.locator('#localsearch-input').fill('GAE')
  await page.locator('.VPLocalSearchBox .result').filter({ hasText: /GAE/ }).first().waitFor({ timeout: 20000 })
  await page.keyboard.press('Escape')
  // Desktop and mobile pages must stay within their viewport; code scrolls within its own box.
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    for (const path of ['/', '/easyspider/chapter-04', '/openclaw/chapter-11', '/langchain/ten-minutes', '/minimind/b00-01', '/minimind/b21-03']) {
      await page.goto(base + path, { waitUntil: 'networkidle' })
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2)
      assert.equal(overflow, false, `Viewport overflow at ${width} ${path}`)
    }
    if (width === 390) {
      await page.screenshot({ path: join(out, 'lecture-mobile.png') })
      await page.locator('.VPLocalNav button.menu').click()
      await page.locator('.VPSidebar.open').waitFor()
      await page.goto(base)
      await page.screenshot({ path: join(out, 'home-mobile.png'), fullPage: true })
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base)
  await page.getByRole('switch', { name: /切换至深色/ }).click()
  assert.ok(await page.locator('html.dark').count())
  await page.screenshot({ path: join(out, 'home-dark.png'), fullPage: true })
  assert.deepEqual(errors, [])
  Object.assign(report, { status: 'passed', runtimeErrors: errors, checked: ['5 project entry links', 'interactive project tabs', 'lecture images', 'local full-text search including GAE', 'source viewer line anchors', 'syntax highlighting', 'mathematical formulas including math fences with attributes', 'MiniMind topic navigation and cleaned Markdown downloads', 'preserved pretraining definition and removed classroom digressions', 'Mermaid diagrams', 'removed learning-route and demo sections', 'desktop and mobile width', 'mobile sidebar', 'dark theme'] })
  console.log('Browser checks passed.')
} catch (error) {
  await page.screenshot({ path: join(out, 'failure.png'), fullPage: false })
  Object.assign(report, { status: 'failed', message: error.message, runtimeErrors: errors })
  throw error
} finally {
  await writeFile(join(out, 'browser.json'), JSON.stringify(report, null, 2))
  await browser.close()
}
